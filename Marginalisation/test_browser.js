"use strict";
const assert = require("node:assert/strict");
require("../TeachingTools/lesson_browser_test.js").runLessonBrowser("Marginalisation", async b => {
  assert.equal(await b.evaluate("document.title"), "From Posterior Landscape to Scientific Answer");
  assert.equal(await b.text("broad-mass"), "65%");
  assert.equal(await b.text("interval-mass"), "15.25%");
  assert.ok(Number(await b.text("mode")) < 0);
  assert.ok(await b.hasColour("marginal", [80, 89, 166]));
  assert.ok(await b.hasColour("joint", [8, 127, 140]), "Interval boundaries must be teal");
  const density = await b.evaluate("lesson.result.joint[90]");
  await b.change("centre", -1);
  assert.deepEqual(await b.evaluate("lesson.result.joint[90]"), density);
  assert.ok(parseFloat(await b.text("interval-mass")) > 25);
  await b.change("show_profile", true);
  assert.deepEqual(await b.evaluate("lesson.result.joint[90]"), density);
  assert.ok(await b.hasColour("marginal", [213, 101, 52]), "Optional profile must actually be plotted, not merely labelled");
  await b.evaluate("document.querySelector('[data-preset=\"tall\"]').click()");
  assert.equal(await b.text("broad-mass"), "70%");
  assert.ok(Number(await b.text("mode")) < 0, "Tall narrow mode must not replace the broad component mass");
  await b.change("width", 2);
  await b.change("weight", 0.95);
  await b.change("centre", 3);
  const mass = parseFloat(await b.text("window-mass"));
  assert.ok(mass < 100 && mass > 99, "Wide finite image must retain its omitted tails");
  const probability = await b.text("interval-mass");
  await b.change("seed", 2147483647);
  assert.equal(await b.text("interval-mass"), probability, "Analytic result must not depend on seed");
  await b.healthy();
  await b.click("reset");
}).catch(error => { console.error(error); process.exitCode = 1; });
