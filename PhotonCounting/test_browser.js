"use strict";
const assert = require("node:assert/strict");
require("../TeachingTools/lesson_browser_test.js").runLessonBrowser("PhotonCounting", async b => {
  assert.equal(await b.evaluate("document.title"), "Counting Photons");
  assert.equal(await b.text("expected-count"), "10");
  assert.ok(await b.hasColour("count-plot", [8, 127, 140]), "Show the exact discrete Poisson masses");
  assert.ok(await b.hasColour("count-plot", [80, 89, 166]), "Show a distinct Gaussian comparison");
  assert.ok(await b.hasColour("stream-plot", [213, 101, 52]), "Show actual event arrivals");
  await b.evaluate(`globalThis.photonExperiment = lesson.result;
    globalThis.finalPhotonCounts = JSON.stringify(lesson.result.frames[60].counts);
    Math.random = () => { throw new Error("Unseeded randomness"); };`);
  await b.click("rewind"); await b.healthy();
  assert.equal(await b.text("expected-count"), "0"); assert.equal(await b.text("stream-count"), "0");
  assert.equal(await b.text("empirical-moments"), "0 / 0");
  assert.equal(await b.text("negative-mass"), "No Gaussian");
  assert.match(await b.text("count-sd"), /undefined/);
  await b.click("step"); assert.ok(Number(await b.text("expected-count")) > 0);
  await b.click("finish");
  assert.equal(await b.evaluate("lesson.result === photonExperiment && JSON.stringify(lesson.result.frames[60].counts) === finalPhotonCounts"), true);
  await b.change("gaussian", "hide");
  assert.equal(await b.evaluate("lesson.result === photonExperiment"), true, "Display-only changes must reuse the whole cached experiment");
  assert.equal(await b.hasColour("count-plot", [80, 89, 166]), false);
  await b.change("gaussian", "show");
  assert.equal(await b.hasColour("count-plot", [80, 89, 166]), true);
  await b.evaluate('document.querySelector(\'[data-preset="few"]\').click()');
  await b.healthy();
  assert.ok(await b.evaluate("lesson.result.frames[60].negativeMass > 0.07 && lesson.result.frames[60].exact[-lesson.result.frames[60].lower] > 0.65"));
  await b.evaluate('document.querySelector(\'[data-preset="dark"]\').click()');
  assert.equal(await b.text("expected-count"), "0");
  assert.equal(await b.text("stream-count"), "0");
  assert.equal(await b.hasColour("stream-plot", [213, 101, 52]), false);
  await b.click("rewind"); await b.click("finish"); await b.healthy();
  await b.change("rate", 8); await b.change("exposure", 20); await b.healthy();
  assert.equal(await b.text("expected-count"), "160");
  assert.ok(await b.evaluate("Math.abs(lesson.result.frames[60].mean-160)<1.3 && lesson.result.frames[60].counts.every(Number.isInteger)"));
  await b.change("gaussian", "rounded-normal-sampler");
  assert.equal(await b.evaluate('document.getElementById("error").hidden'), false);
  assert.equal(await b.evaluate('document.getElementById("play").disabled'), true);
  await b.click("reset"); await b.healthy();
  await b.change("seed", 2147483647); await b.click("redraw");
  assert.equal(await b.evaluate("lesson.result.base.seed"), 0, "New-realisation seeds must wrap safely");
  await b.evaluate("globalThis.wrappedPhotons = lesson.result");
  await b.change("gaussian", "hide");
  assert.equal(await b.evaluate("lesson.result === wrappedPhotons"), true);
  await b.click("reset");
}).catch(error => { console.error(error); process.exitCode = 1; });
