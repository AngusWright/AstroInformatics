"use strict";
const assert = require("node:assert/strict");
require("../TeachingTools/lesson_browser_test.js").runLessonBrowser("MultipleTesting", async b => {
  assert.equal(await b.evaluate("document.title"), "Looking-elsewhere: A Sky Full of False Discoveries");
  assert.equal(await b.text("tested"), "1600 / 1600");
  assert.equal(await b.text("global-p"), "88.48%");
  assert.equal(await b.text("discoveries"), "0 / 0");
  assert.equal(await b.text("fdp"), "No discoveries");
  const sky = await b.evaluate("lesson.result.cells.map(c => c.z)");
  await b.change("threshold", 1.5);
  assert.deepEqual(await b.evaluate("lesson.result.cells.map(c => c.z)"), sky);
  assert.ok(await b.hasColour("sky", [213, 101, 52]), "False discoveries must have real orange rings");
  assert.ok(await b.hasColour("risk", [80, 89, 166]), "Global-risk curve must be drawn");
  const local = Number(await b.text("local-p"));
  await b.change("tails", "two");
  assert.ok(Math.abs(Number(await b.text("local-p")) / local - 2) < 0.001);
  assert.deepEqual(await b.evaluate("lesson.result.cells.map(c => c.z)"), sky);
  await b.change("side", 5);
  assert.deepEqual(await b.evaluate("lesson.result.cells.map(c => c.z)"), sky.slice(0, 25));
  await b.click("rewind");
  assert.equal(await b.text("tested"), "0 / 25");
  assert.equal(await b.text("global-p"), "0%");
  await b.click("step");
  assert.equal(await b.text("tested"), "0 / 25", "A 1% step may legitimately reveal no cell in a 25-cell search");
  await b.click("finish");
  await b.evaluate("document.querySelector('[data-preset=\"sources\"]').click()");
  assert.ok(await b.hasColour("sky", [8, 127, 140]), "Injected true discoveries must have teal rings");
  assert.ok(await b.evaluate("lesson.result.cells.some(c => c.truth && c.hit)"));
  await b.click("redraw");
  const newSky = await b.evaluate("lesson.result.cells.map(c => c.z)");
  await b.change("threshold", 5);
  assert.deepEqual(await b.evaluate("lesson.result.cells.map(c => c.z)"), newSky);
  await b.evaluate("document.getElementById('frame').value = '37'; document.getElementById('frame').dispatchEvent(new Event('input'))");
  assert.deepEqual(await b.evaluate("lesson.result.cells.map(c => c.z)"), newSky);
  await b.healthy();
  await b.click("reset");
}).catch(error => { console.error(error); process.exitCode = 1; });
