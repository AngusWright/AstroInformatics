"use strict";
const assert = require("node:assert/strict");
require("../TeachingTools/lesson_browser_test.js").runLessonBrowser("BaseRates", async b => {
  assert.equal(await b.evaluate("document.title"), "Anomoly Detection: Why Reliable Detectors Still Find Impostors");
  assert.equal(await b.text("ppv"), "48.97%");
  assert.equal(await b.text("candidate-count"), "86 / 175");
  assert.ok(await b.hasColour("mosaic", [8, 127, 140]));
  assert.ok(await b.hasColour("mosaic", [213, 101, 52]));
  const identities = await b.evaluate("[lesson.result.truth, lesson.result.flagged]");
  await b.change("reveal", "hide");
  assert.deepEqual(await b.evaluate("[lesson.result.truth, lesson.result.flagged]"), identities);
  assert.equal(await b.text("candidate-count"), "Hidden / 175");
  assert.equal(await b.text("realised"), "Hidden");
  assert.ok(await b.hasColour("mosaic", [80, 89, 166]));
  assert.equal(await b.hasColour("mosaic", [213, 101, 52]), false);
  assert.ok(await b.hasColour("counts", [80, 89, 166]), "Hidden realised composition must not leak via count colours");
  await b.change("reveal", "show");
  await b.click("rewind");
  assert.equal(await b.text("candidate-count"), "0 / 0");
  assert.equal(await b.text("realised"), "Undefined (no flags)");
  assert.equal(await b.text("ppv"), "48.97%", "PPV is not the observed empty-sample fraction");
  await b.click("step");
  assert.equal(await b.text("scanned"), "100 / 10000");
  assert.deepEqual(await b.evaluate("[lesson.result.truth, lesson.result.flagged]"), identities);
  await b.click("finish");
  await b.change("log_prevalence", -6);
  const rarePpv = parseFloat(await b.text("ppv"));
  assert.ok(rarePpv > 0 && rarePpv < 0.01, "Rare-event posterior must not be rounded to zero");
  await b.change("false_positive", 0);
  assert.equal(await b.text("ppv"), "100%");
  assert.equal(await b.text("candidate-count"), "0 / 0");
  assert.equal(await b.text("realised"), "Undefined (no flags)");
  await b.change("log_prevalence", -1);
  await b.change("sensitivity", 1);
  assert.ok(await b.evaluate("lesson.result.truth.every((real, i) => real === lesson.result.flagged[i])"));
  await b.click("redraw");
  const newSurvey = await b.evaluate("lesson.result.flagged");
  await b.change("reveal", "hide");
  assert.deepEqual(await b.evaluate("lesson.result.flagged"), newSurvey);
  await b.healthy();
  await b.click("reset");
}).catch(error => { console.error(error); process.exitCode = 1; });
