"use strict";
const assert = require("node:assert/strict");
require("../TeachingTools/lesson_browser_test.js").runLessonBrowser("ForwardModelling", async b => {
  assert.equal(await b.evaluate("document.title"), "Uncertain Encounters, Many Possible Galaxies");
  assert.equal(await b.text("model-time"), "8.0");
  assert.ok(await b.hasColour("encounter-plot", [8, 127, 140]), "The nominal disc must be plotted");
  assert.ok(await b.hasColour("encounter-plot", [213, 101, 52]), "The nominal perturber must be plotted");
  await b.evaluate(`globalThis.savedEncounter = lesson.result;
    Math.random = () => { throw new Error("Unseeded randomness"); };`);
  await b.click("rewind");
  assert.equal(await b.text("model-time"), "0.0");
  assert.equal(await b.text("outside-median"), "0%");
  await b.click("step"); assert.equal(await b.text("model-time"), "0.1");
  await b.click("finish");
  assert.equal(await b.evaluate("lesson.result === savedEncounter"), true, "Playback must not integrate or sample again");
  await b.evaluate('document.querySelector(\'[data-preset="close"]\').click()');
  await b.healthy();
  assert.equal(await b.value("uncertainty"), "0.35", "The retained close-encounter example must be a valid slider value");
  assert.ok(await b.evaluate("lesson.result.summaries[80].max > lesson.result.summaries[80].min"));
  assert.ok(await b.hasColour("spread-plot", [80, 89, 166]), "Plot the diagnostic spread, not just a particle animation");
  await b.change("uncertainty", 0);
  assert.equal(await b.evaluate("lesson.result.ensemble.every(path => JSON.stringify(path) === JSON.stringify(lesson.result.nominal))"), true);
  await b.change("impact", 0.4); await b.change("speed", 0.6); await b.change("uncertainty", 0.4);
  await b.change("seed", 0); await b.healthy();
  assert.equal(await b.evaluate("lesson.result.nominal.flat(2).every(Number.isFinite)"), true);
  await b.change("impact", 99);
  assert.equal(await b.value("impact"), "3", "The range control must enforce its physical boundary");
  await b.healthy();
  await b.change("seed", 0.5);
  assert.equal(await b.evaluate('document.getElementById("error").hidden'), false);
  assert.equal(await b.text("model-time"), "—");
  await b.click("reset"); await b.healthy();
  await b.click("redraw");
  await b.evaluate("globalThis.nextEncounter = lesson.result");
  await b.click("rewind"); await b.click("finish");
  assert.equal(await b.evaluate("lesson.result === nextEncounter && lesson.generation === 1"), true);
  await b.click("reset");
}).catch(error => { console.error(error); process.exitCode = 1; });
